-- Removes the FAQ feature's table, if it still exists in a database that has not
-- been migrated yet. The page, the admin editor, the API routes, the DTOs and
-- every reference in the code are gone; the table was the last thing left.
--
-- Idempotent: a database restored from a dump taken after the drop, or a second
-- run, simply reports that there is nothing to do. It also refuses to drop a
-- table that still holds rows, so an unforeseen database cannot silently lose
-- content.
--
-- Rollback: restore the table from the pre-migration dump, or recreate it:
--   CREATE TABLE faqs (
--     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
--     created_at TIMESTAMP(6), updated_at TIMESTAMP(6),
--     answer VARCHAR(2000) NOT NULL, question VARCHAR(255) NOT NULL,
--     display_order INTEGER NOT NULL
--   );

BEGIN;

DO $$
BEGIN
  IF to_regclass('public.faqs') IS NULL THEN
    RAISE NOTICE 'faqs table is already absent; nothing to drop';
    RETURN;
  END IF;
  IF (SELECT COUNT(*) FROM faqs) <> 0 THEN
    RAISE EXCEPTION 'faqs table is not empty; aborting drop';
  END IF;
END $$;

DROP TABLE IF EXISTS faqs;
DROP SEQUENCE IF EXISTS faqs_id_seq;

COMMIT;
