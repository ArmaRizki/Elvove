-- Client photo selection: the raw photos live in a Google Drive folder per
-- booking, the client opens a token link to pick which ones to edit, and the
-- picked originals are copied into a "mustedit" folder next to them.
--
-- packages.photo_selection_limit is the entitlement ("Origin: 10 photos").
-- bookings.selection_limit snapshots it at booking time for the same reason
-- package_title and package_price are snapshotted: changing the package later
-- must not change what a customer already booked.
--
-- selection_token is the only key that opens the client page. It is generated
-- with crypto/rand at booking time, so the link exists without the admin having
-- to create it, and the page refuses to show photos until raw_folder_id is set.
--
-- booking_photos is a cache of what the Drive folder holds: one row per image,
-- with the Drive id of its WebP thumbnail (webp_file_id) so the conversion runs
-- once, and the selection itself (selected, position).
--
-- All columns are additive and nullable, so an older backend keeps working
-- against the new schema.
--
-- Apply with:
--   psql "$DATABASE_URL" -f db/migrations/2026-11-16-photo-selection.sql

BEGIN;

ALTER TABLE packages
    ADD COLUMN IF NOT EXISTS photo_selection_limit integer NOT NULL DEFAULT 0;

ALTER TABLE bookings
    ADD COLUMN IF NOT EXISTS raw_folder_id character varying(100);

ALTER TABLE bookings
    ADD COLUMN IF NOT EXISTS selection_token character varying(64);

ALTER TABLE bookings
    ADD COLUMN IF NOT EXISTS selection_limit integer;

ALTER TABLE bookings
    ADD COLUMN IF NOT EXISTS selection_folder_id character varying(100);

ALTER TABLE bookings
    ADD COLUMN IF NOT EXISTS selection_submitted_at timestamp(6);

-- Two bookings must never share a link: one token, one customer's photos.
CREATE UNIQUE INDEX IF NOT EXISTS bookings_selection_token_key
    ON bookings (selection_token)
    WHERE selection_token IS NOT NULL;

CREATE TABLE IF NOT EXISTS booking_photos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    drive_file_id character varying(100) NOT NULL,
    file_name character varying(255) NOT NULL,
    width integer,
    height integer,
    webp_file_id character varying(100),
    selected boolean NOT NULL DEFAULT false,
    position integer,
    created_at timestamp(6) DEFAULT NOW(),
    updated_at timestamp(6) DEFAULT NOW(),
    CONSTRAINT booking_photos_booking_file_key UNIQUE (booking_id, drive_file_id)
);

CREATE INDEX IF NOT EXISTS booking_photos_booking_idx ON booking_photos (booking_id);

-- Photos converted but not selected are still converted, so the index above is
-- enough; this one serves the "only the picked ones" copy on submit.
CREATE INDEX IF NOT EXISTS booking_photos_selected_idx
    ON booking_photos (booking_id, position)
    WHERE selected;

COMMIT;

