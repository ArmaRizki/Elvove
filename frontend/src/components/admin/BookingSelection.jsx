import { useRef, useState } from "react";
import { Check, Copy, ExternalLink, FolderOpen, LoaderCircle, Save } from "lucide-react";
import { adminApi } from "../../services/adminApi";
import { adminInput, adminLabel, adminNotice, adminSecondaryButton } from "./adminStyles";
import { formatDateTime } from "./adminFormat";

/**
 * The raw photo folder, the client's selection link and how far the client got.
 *
 * <p>The link opens /pilih/<token>. It travels inside the settlement e-mail, so
 * the admin only has to save the Drive folder here; the token is created with
 * the booking and does not have to be generated by hand.</p>
 */
export default function BookingSelection({ booking, onUpdated }) {
  const [link, setLink] = useState(booking?.rawFolderId ? driveFolderLink(booking.rawFolderId) : "");
  const [saving, setSaving] = useState(false);
  const [notice, setNotice] = useState({ type: "", text: "" });
  const [copied, setCopied] = useState(false);
  const inFlight = useRef(false);

  if (!booking) return null;

  const saved = booking.rawFolderId || "";
  const limit = Number(booking.selectionLimit) || 0;
  const photoCount = Number(booking.photoCount) || 0;
  const selectedCount = Number(booking.selectedCount) || 0;
  const submittedAt = formatDateTime(booking.selectionSubmittedAt);
  const clientURL = booking.selectionToken
    ? `${window.location.origin}/pilih/${booking.selectionToken}`
    : "";

  const save = async () => {
    if (inFlight.current) return;
    inFlight.current = true;
    setSaving(true);
    setNotice({ type: "", text: "" });
    try {
      const { data } = await adminApi.updateBookingRawFolder(booking.id, link.trim());
      onUpdated?.(data);
      setNotice({
        type: "success",
        text: link.trim()
          ? "Folder foto tersimpan. Link pilihan foto ikut terkirim di email pelunasan."
          : "Folder foto dikosongkan.",
      });
    } catch (error) {
      setNotice({
        type: "error",
        text: error.response?.data?.message || "Folder foto gagal disimpan.",
      });
    } finally {
      inFlight.current = false;
      setSaving(false);
    }
  };

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(clientURL);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 2000);
    } catch {
      setNotice({ type: "error", text: "Link tidak bisa disalin otomatis. Salin manual dari kolom di atas." });
    }
  };

  const changed = link.trim() !== (saved ? driveFolderLink(saved) : "");

  return (
    <div className="space-y-4">
      <div>
        <label className={adminLabel} htmlFor="booking-raw-folder">
          FOLDER FOTO MENTAH (GOOGLE DRIVE)
        </label>
        <div className="mt-1 flex flex-col gap-2 sm:flex-row">
          <input
            id="booking-raw-folder"
            type="text"
            placeholder="https://drive.google.com/drive/folders/..."
            value={link}
            onChange={(event) => setLink(event.target.value)}
            className={adminInput}
          />
          <button
            type="button"
            onClick={save}
            disabled={!changed || saving}
            aria-busy={saving}
            className={`${adminSecondaryButton} shrink-0`}
          >
            {saving ? <LoaderCircle size={16} className="animate-spin" /> : <Save size={16} />}
            Simpan Folder
          </button>
        </div>
        <p className="mt-1 text-xs text-gray-500">
          Tempel link folder Drive berisi foto mentah. Elvove membuat pratinjau WebP di subfolder
          <span className="mx-1 font-mono">webp</span> dan menyalin foto pilihan ke
          <span className="mx-1 font-mono">mustedit</span>.
        </p>
      </div>

      {clientURL && (
        <div>
          <label className={adminLabel} htmlFor="booking-selection-link">
            LINK PILIHAN FOTO UNTUK KLIEN
          </label>
          <div className="mt-1 flex flex-col gap-2 sm:flex-row">
            <input id="booking-selection-link" readOnly value={clientURL} className={adminInput} />
            <div className="flex shrink-0 gap-2">
              <button type="button" onClick={copy} className={adminSecondaryButton}>
                {copied ? <Check size={16} /> : <Copy size={16} />}
                {copied ? "Tersalin" : "Salin"}
              </button>
              <a
                href={clientURL}
                target="_blank"
                rel="noreferrer"
                className={adminSecondaryButton}
                aria-label="Buka halaman pilihan foto"
              >
                <ExternalLink size={16} />
              </a>
            </div>
          </div>
          <p className="mt-1 text-xs text-gray-500">
            Link ini otomatis ikut di email pelunasan saat folder foto mentah sudah diisi.
          </p>
        </div>
      )}

      <div className="grid grid-cols-1 gap-2 text-xs text-gray-600 sm:grid-cols-2">
        <p className="flex items-center gap-2">
          <FolderOpen size={14} className="shrink-0 text-gray-400" />
          {limit > 0 ? `Kuota pilih ${limit} foto` : "Paket ini belum punya kuota pilih foto"}
        </p>
        <p>
          {photoCount} foto terdeteksi · {selectedCount} dipilih klien
        </p>
        {submittedAt && (
          <p className="text-green-700">Pilihan dikirim pada {submittedAt}</p>
        )}
      </div>

      {notice.text && (
        <p className={adminNotice(notice.type)} role="status">
          {notice.text}
        </p>
      )}
    </div>
  );
}

// driveFolderLink turns the stored folder id back into a link an admin can open.
function driveFolderLink(id) {
  return `https://drive.google.com/drive/folders/${id}`;
}
